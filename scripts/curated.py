def _pos_ok(row, lat, lon):
    if not (_num(lat) and _num(lon)):
        return True
    rlat, rlon = row.get("lat"), row.get("lon")
    if not (_num(rlat) and _num(rlon)):
        return True
    return abs(rlat - lat) < MATCH_DEG and abs(rlon - lon) < MATCH_DEG


def _kel_ok(row, kel):
    if not kel:
        return True
    village = row.get("village")
    if not village:
        return True
    return _norm_text(village) == _norm_text(kel)


def _find_poi_targets(clean, pending, match):
    """Kandidat sasaran sebuah op match: (bentuk, lapisan, baris)."""
    name = match.get("name")
    kind = match.get("kind")
    lat, lon = match.get("lat"), match.get("lon")
    kel = match.get("kelurahan")
    cands = []
    if name:
        nw = _norm_text(name)
        for layer in POI_LAYERS:
            for row in clean[layer][LAYERS[layer]["rows"]]:
                if _norm_text(row.get("name")) != nw:
                    continue
                if not _pos_ok(row, lat, lon) or not _kel_ok(row, kel):
                    continue
                cands.append(("row", layer, row))
        for row in pending.values():
            if _norm_text(row.get("name")) != nw or not _pos_ok(row, lat, lon):
                continue
            cands.append(("add", KURASI_LAYER, row))
    else:
        for layer in POI_LAYERS:
            for row in clean[layer][LAYERS[layer]["rows"]]:
                if _pos_ok(row, lat, lon):
                    cands.append(("row", layer, row))
        for row in pending.values():
            if _pos_ok(row, lat, lon):
                cands.append(("add", KURASI_LAYER, row))
    if kind and len(cands) > 1:
        want = KIND_LAYERS.get(kind) or set()
        narrowed = [c for c in cands if c[1] in want or c[0] == "add"]
        if narrowed:
            cands = narrowed
    return cands


def _ruas_hits(roads_doc, name):
    for norm in (_norm_text(name), _norm_road(name)):
        hits = []
        for c in roads_doc.get("classes") or []:
            for r in c.get("roads") or []:
                for m in r.get("matched") or []:
                    if _norm_text(m) == norm or _norm_road(m) == norm:
                        hits.append((c, r))
                        break
        if hits:
            return hits
    return []


def resolve(curation, payloads, labels=None, district_of=None):
    """Petakan dokumen kurasi atlas ke entri curated.json + model pratinjau.

    payloads = {'schools': dok, 'puskesmas': dok, 'faskes': dok, 'roads': dok}
    (dokumen yang sedang ter-commit; fungsi ini membalikkan kurasi lama dulu).

    Kembalikan {'pois': [...], 'roads': [...], 'skipped': [...], 'errors': [...],
    'preview': {'pois': [...], 'roads': [...]}}.
    """
    labels = labels or {}
    district_of = district_of or {}

    clean = {}
    for layer in POI_LAYERS:
        d = json.loads(json.dumps(payloads[layer]))
        pristine(layer, d)
        clean[layer] = d
    roads_doc = json.loads(json.dumps(payloads["roads"]))
    pristine("roads", roads_doc)

    out = {"pois": [], "roads": [], "skipped": [], "errors": [],
           "preview": {"pois": [], "roads": []}}
    pending = {}          # key -> baris add yang masih hidup
    ruas_pick = {}        # (group, n) -> id op terakhir

    def note(msg):
        out["errors"].append(msg)

    # -- titik --
    for op in curation.get("pois") or []:
        if not isinstance(op, dict):
            continue
        oid = str(op.get("id") or f"?{len(out['preview']['pois'])}")
        o = op.get("op")

        if o == "add":
            kel = op.get("kelurahan") or ""
            kind = op.get("kind") or ""
            row = {
                "key": oid, "name": (op.get("name") or "").strip(),
                "kind": kind, "label": labels.get(kind, kind),
                "lat": op.get("lat"), "lon": op.get("lon"),
                "village": kel,
                "district": district_of.get(kel, ""),
                "reason": op.get("reason") or "", "source": op.get("source") or "",
            }
            entry = {"id": oid, "op": "add", "layer": KURASI_LAYER, "row": row,
                     "reason": row["reason"], "source": row["source"]}
            out["pois"].append(entry)
            pending[oid] = row
            out["preview"]["pois"].append({
                "id": oid, "op": "add", "status": "tambah", "layer": KURASI_LAYER,
                "key": oid, "name": row["name"], "row": row, "changes": [], "notes": [],
            })
            continue

        if o not in ("set", "remove"):
            continue
        match = op.get("match") or {}
        subject = (match.get("name")
                   or (f'{match.get("lat")},{match.get("lon")}' if _num(match.get("lat")) else "?"))
        cands = _find_poi_targets(clean, pending, match)

        if len(cands) > 1:
            note(f'{oid}: match ambigu — {len(cands)} kandidat di depok-map: '
                 + ", ".join(f'{c[1]}/{c[2].get("name")}' for c in cands[:4])
                 + ". Persempit match (name/kind atau lon+lat).")
            out["preview"]["pois"].append({
                "id": oid, "op": o, "status": "ambigu", "layer": None, "key": None,
                "name": subject, "changes": [], "notes": [],
            })
            continue

        if not cands:
            why = ("tidak ada baris sekolah/puskesmas/faskes yang cocok — "
                   "suntingan hanya berlaku di atlas")
            out["skipped"].append({"id": oid, "section": "pois",
                                   "subject": subject, "why": why})
            out["preview"]["pois"].append({
                "id": oid, "op": o, "status": "dilewati", "layer": None, "key": None,
                "name": subject, "changes": [], "notes": [why],
            })
            continue

        form, layer, row = cands[0]

        if o == "remove":
            if form == "add":
                pending.pop(row["key"], None)
                for e in out["pois"]:
                    if e.get("row", {}).get("key") == row["key"]:
                        out["pois"].remove(e)
                for pv in out["preview"]["pois"]:
                    if pv.get("key") == row["key"] and pv.get("op") == "add":
                        pv["status"] = "batal"
                        pv["notes"].append(f"{oid}: titik tambahan dibatalkan oleh remove")
                out["preview"]["pois"].append({
                    "id": oid, "op": "remove", "status": "batal", "layer": KURASI_LAYER,
                    "key": row["key"], "name": subject, "changes": [],
                    "notes": ["titik tambahan dibatalkan — tidak diekspor"],
                })
                continue
            entry = {"id": oid, "op": "remove", "layer": layer, "key": row.get("key"),
                     "name": row.get("name"), "reason": op.get("reason") or "",
                     "source": op.get("source") or ""}
            out["pois"].append(entry)
            idx = clean[layer][LAYERS[layer]["rows"]].index(row)
            clean[layer][LAYERS[layer]["rows"]].pop(idx)
            out["preview"]["pois"].append({
                "id": oid, "op": "remove", "status": "hapus", "layer": layer,
                "key": row.get("key"), "name": row.get("name"), "changes": [],
                "notes": [],
            })
            continue

        # set
        st = dict(op.get("set") or {})
        if form == "add":
            changes = []
            for k in ("name", "kind", "lat", "lon"):
                if k in st:
                    changes.append([k, row.get(k), st[k]])
                    row[k] = st[k]
            if "kind" in st:
                row["label"] = labels.get(st["kind"], st["kind"])
            out["preview"]["pois"].append({
                "id": oid, "op": "set", "status": "gabung", "layer": KURASI_LAYER,
                "key": row["key"], "name": row["name"], "changes": changes,
                "notes": ["digabung ke titik tambahan"],
            })
            continue

        mapped, changes, notes = {}, [], []
        for k in ("name", "lat", "lon"):
            if k in st:
                mapped[k] = st[k]
        if "kind" in st:
            if layer == "faskes":
                fk = FASKES_KIND_MAP.get(st["kind"])
                if fk:
                    mapped["kind"] = fk
                else:
                    notes.append(f'kind "{st["kind"]}" tidak punya padanan di lapisan faskes')
            else:
                notes.append(f'kind tidak diekspor ke lapisan {layer} (data resmi)')
        for k, v in mapped.items():
            changes.append([k, row.get(k), v])
            row[k] = v
        if not mapped:
            why = "tidak ada bidang yang bisa diekspor ke depok-map"
            out["skipped"].append({"id": oid, "section": "pois",
                                   "subject": subject, "why": why})
            out["preview"]["pois"].append({
                "id": oid, "op": "set", "status": "dilewati", "layer": layer,
                "key": row.get("key"), "name": subject, "changes": [], "notes": notes + [why],
            })
            continue
        entry = {"id": oid, "op": "set", "layer": layer, "key": row.get("key"),
                 "name": subject, "set": mapped, "reason": op.get("reason") or "",
                 "source": op.get("source") or ""}
        out["pois"].append(entry)
        out["preview"]["pois"].append({
            "id": oid, "op": "set", "status": "ubah", "layer": layer,
            "key": row.get("key"), "name": subject, "changes": changes,
            "notes": notes,
        })

    # -- jalan --
    for op in curation.get("roads") or []:
        if not isinstance(op, dict):
            continue
        oid = str(op.get("id") or "?")
        name = (op.get("match") or "").strip()
        cls = op.get("class")
        if cls not in ROAD_CLASSES:
            note(f"{oid}: class jalan tidak dikenal: {cls!r}")
            continue
        hits = _ruas_hits(roads_doc, name)
        if len(hits) > 1:
            note(f'{oid}: match jalan "{name}" ambigu — {len(hits)} ruas Perda: '
                 + ", ".join(f'{c["key"]}/{r["n"]}' for c, r in hits[:4]) + ".")
            out["preview"]["roads"].append({
                "id": oid, "status": "ambigu", "subject": name, "group": None,
                "n": None, "ruas": None, "badge_before": None,
                "badge_after": None, "notes": [],
            })
            continue
        if not hits:
            why = ("tidak ada padanan di 77 ruas Perda — suntingan hanya "
                   "berlaku di atlas")
            out["skipped"].append({"id": oid, "section": "roads",
                                   "subject": name, "why": why})
            out["preview"]["roads"].append({
                "id": oid, "status": "dilewati", "subject": name, "group": None,
                "n": None, "ruas": None, "badge_before": None, "badge_after": None,
                "notes": [why],
            })
            continue
        c, r = hits[0]
        badge_after = f'{CLASS_LABEL[cls]} {BADGE_SUFFIX}'
        entry = {"id": oid, "op": "set-class", "group": c["key"], "n": r["n"],
                 "match": name, "class": cls, "reason": op.get("reason") or "",
                 "source": op.get("source") or ""}
        key = (c["key"], r["n"])
        if key in ruas_pick:
            out["roads"] = [e for e in out["roads"]
                            if (e.get("group"), e.get("n")) != key]
            for pv in out["preview"]["roads"]:
                if (pv.get("group"), pv.get("n")) == key:
                    pv["status"] = "tergantikan"
                    pv["notes"].append(f"digantikan {oid}")
        out["roads"].append(entry)
        ruas_pick[key] = oid
        out["preview"]["roads"].append({
            "id": oid, "status": "ubah", "subject": name, "group": c["key"],
            "n": r["n"], "ruas": r.get("name"),
            "badge_before": r.get("badge_perda") or r.get("badge"),
            "badge_after": badge_after, "notes": [],
        })

    return out


def build_doc(model, generated):
    """Rakit dokumen curated.json final dari keluaran resolve()."""
    return {
        "version": VERSION,
        "generated": generated,
        "generator": "Studio Atlas (ensiklopedia-kota) — tools/data/curation.json",
        "note": "Berkas hasil ekspor Studio Atlas. Jangan disunting tangan.",
        "pois": model.get("pois") or [],
        "roads": model.get("roads") or [],
        "skipped": model.get("skipped") or [],
    }


def summary(model):
    """Angka ringkas untuk laporan/pratinjau."""
    def by_status(rows):
        out = {}
        for r in rows:
            out[r.get("status")] = out.get(r.get("status"), 0) + 1
        return out
    return {
        "pois": by_status(model.get("preview", {}).get("pois") or []),
        "roads": by_status(model.get("preview", {}).get("roads") or []),
        "skipped": len(model.get("skipped") or []),
        "errors": len(model.get("errors") or []),
    }
