# ---------- bantu ----------

def _spec(layer):
    try:
        return LAYERS[layer]
    except KeyError:
        raise KeyError(f"lapisan tidak dikenal: {layer}") from None


def _norm_text(s):
    return re.sub(r"\s+", " ", re.sub(r"[^0-9a-z]+", " ", str(s or "").casefold())).strip()


def _norm_road(s):
    n = _norm_text(s)
    for pre in ("jalan ", "jl ", "jln "):
        if n.startswith(pre):
            return n[len(pre):]
    return n


def _num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


# ---------- berkas ----------

def read_payload(layer, root=ROOT):
    """(teks, dokumen) dari src/<berkas>.js. Melempar bila pola tak ditemukan."""
    spec = _spec(layer)
    path = Path(root) / spec["file"]
    text = path.read_text(encoding="utf-8")
    m = re.search(r"window\." + spec["var"] + r"\s*=\s*(\{.*\})\s*;\s*$", text, re.S)
    if not m:
        raise ValueError(f'{spec["file"]}: window.{spec["var"]} tidak ditemukan')
    return text, json.loads(m.group(1))


def encode(layer, doc, mark=False):
    """Teks berkas lengkap untuk sebuah dokumen payload (format skrip build)."""
    spec = _spec(layer)
    head = spec["mark"] if (mark and spec["mark"]) else spec["base"]
    return head + spec["open"] + json.dumps(doc, **spec["dump"]) + ";\n"


def write_text(path, text):
    """Tulis atomik (berkas sementara di folder yang sama, lalu replace)."""
    path = Path(path)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix="." + path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def load_doc(root=ROOT):
    """Dokumen curated.json, atau None bila berkas belum ada."""
    path = Path(root) / CURATED_REL
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def empty_doc():
    return {"version": VERSION, "pois": [], "roads": []}


def save_doc(doc, root=ROOT):
    path = Path(root) / CURATED_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text(path, json.dumps(doc, ensure_ascii=False, indent=1) + "\n")


# ---------- validasi skema ----------

def _v_rs(e, at, errs):
    for key in ("reason", "source"):
        v = e.get(key)
        if not isinstance(v, str) or not v.strip():
            errs.append(f'{at}: "{key}" wajib diisi (alasan + sumber)')


def validate(doc):
    """Validasi skema curated.json; kembalikan daftar galat ([] bila bersih)."""
    errs = []
    if not isinstance(doc, dict):
        return ["curated: dokumen harus objek JSON"]
    if doc.get("version") != VERSION:
        errs.append(f'curated: "version" harus {VERSION}')
    pois = doc.get("pois")
    roads = doc.get("roads")
    if not isinstance(pois, list):
        errs.append('curated: "pois" harus daftar')
        pois = []
    if not isinstance(roads, list):
        errs.append('curated: "roads" harus daftar')
        roads = []

    seen = set()
    for i, e in enumerate(pois):
        at = f"pois[{i}]"
        if not isinstance(e, dict):
            errs.append(f"{at}: entri harus objek")
            continue
        eid = e.get("id")
        if not isinstance(eid, str) or not eid.strip():
            errs.append(f"{at}: id wajib diisi")
        _v_rs(e, at, errs)
        o = e.get("op")
        if o == "add":
            if e.get("layer") != KURASI_LAYER:
                errs.append(f'{at}: op add harus layer "{KURASI_LAYER}"')
            row = e.get("row")
            if not isinstance(row, dict):
                errs.append(f"{at}: row wajib objek")
                continue
            for key in ("key", "name", "kind", "village"):
                v = row.get(key)
                if not isinstance(v, str) or not v.strip():
                    errs.append(f"{at}: row.{key} wajib diisi")
            for key in ("lat", "lon"):
                if not _num(row.get(key)):
                    errs.append(f"{at}: row.{key} harus angka")
        elif o in ("set", "remove"):
            layer = e.get("layer")
            if layer not in POI_LAYERS:
                errs.append(f"{at}: layer harus salah satu {POI_LAYERS} untuk {o}")
                continue
            key = e.get("key")
            if not isinstance(key, str) or not key.strip():
                errs.append(f"{at}: key wajib diisi")
            if o == "set":
                st = e.get("set")
                if not isinstance(st, dict) or not st:
                    errs.append(f"{at}: set wajib objek berisi minimal satu perubahan")
                    continue
                allowed = SETTABLE[layer]
                for k, v in st.items():
                    if k not in allowed:
                        errs.append(f'{at}: set.{k} tidak didukung layer "{layer}" '
                                    f"(boleh: {', '.join(allowed)})")
                    elif k == "name":
                        if not isinstance(v, str) or not v.strip():
                            errs.append(f"{at}: set.name wajib teks")
                    elif k == "kind":
                        if layer == "faskes" and v not in FASKES_KINDS:
                            errs.append(f"{at}: set.kind faskes harus salah satu {FASKES_KINDS}")
                    elif not _num(v):
                        errs.append(f"{at}: set.{k} harus angka")
                if ("lon" in st) != ("lat" in st):
                    errs.append(f"{at}: set.lon dan set.lat harus bersamaan")
        else:
            errs.append(f"{at}: op harus add|set|remove")
        if isinstance(eid, str):
            tgt = (e.get("op"), e.get("layer"), e.get("key"))
            if e.get("op") in ("set", "remove"):
                if tgt in seen:
                    errs.append(f"{at}: sasaran ganda — {e.get('layer')}/"
                                f"{e.get('key')} sudah punya op {e.get('op')} lain")
                seen.add(tgt)

    seenr = set()
    for i, e in enumerate(roads):
        at = f"roads[{i}]"
        if not isinstance(e, dict):
            errs.append(f"{at}: entri harus objek")
            continue
        if not isinstance(e.get("id"), str) or not e["id"].strip():
            errs.append(f"{at}: id wajib diisi")
        _v_rs(e, at, errs)
        if e.get("op") != "set-class":
            errs.append(f"{at}: op harus set-class")
            continue
        if e.get("group") not in ROAD_GROUPS:
            errs.append(f"{at}: group harus salah satu {ROAD_GROUPS}")
        if not isinstance(e.get("n"), str) or not e["n"].strip():
            errs.append(f"{at}: n (kode ruas) wajib diisi")
        if not isinstance(e.get("match"), str) or not e["match"].strip():
            errs.append(f"{at}: match (nama jalan) wajib diisi")
        if e.get("class") not in ROAD_CLASSES:
            errs.append(f"{at}: class harus arteri|kolektor|lokal")
        tgt = (e.get("group"), e.get("n"))
        if tgt in seenr:
            errs.append(f"{at}: ruas ganda — {tgt[0]}/{tgt[1]} sudah punya set-class")
        seenr.add(tgt)
    return errs


# ---------- pembalikan (revert) ----------

def pristine(layer, doc):
    """Kembalikan `doc` ke keadaan sebelum kurasi (di tempat).

    Kembalikan jumlah efek yang dibalikkan (0 = dokumen sudah bersih).
    """
    spec = _spec(layer)
    n = 0
    prov = doc.pop("_kurasi", None)
    if prov is not None:
        rows = doc.get(spec["rows"]) or []
        for item in sorted(prov.get("removed") or [], key=lambda i: i["index"]):
            rows.insert(min(int(item["index"]), len(rows)), item["row"])
            n += 1
        if "counts" in prov:
            doc["counts"] = prov["counts"]
            n += 1
    if layer == "roads":
        for c in doc.get("classes") or []:
            for r in c.get("roads") or []:
                if "kurasi" in r or "badge_perda" in r:
                    r.pop("kurasi", None)
                    if "badge_perda" in r:
                        r["badge"] = r.pop("badge_perda")
                    n += 1
    else:
        for row in doc.get(spec["rows"]) or []:
            pv = row.pop("_kurasi", None)
            if not pv:
                continue
            row.update(pv.get("old") or {})
            for k in pv.get("absent") or []:
                row.pop(k, None)
            n += 1
    return n


# ---------- penerapan ----------

def entries_for(layer, doc):
    """Entri kurasi yang menyasar lapisan payload (add tidak menyentuh berkas ini)."""
    if layer == "roads":
        return [e for e in (doc.get("roads") or []) if isinstance(e, dict)]
    return [e for e in (doc.get("pois") or [])
            if isinstance(e, dict) and e.get("op") in ("set", "remove")
            and e.get("layer") == layer]


def _adds(doc):
    return [e for e in (doc.get("pois") or [])
            if isinstance(e, dict) and e.get("op") == "add"]


def _apply_rows(layer, entries, doc):
    spec = _spec(layer)
    rows = doc.get(spec["rows"]) or []
    index = {}
    for row in rows:
        if row.get("key") is not None:
            index.setdefault(row["key"], row)
    errs = []
    rep = {"set": 0, "remove": 0, "lines": []}
    for e in entries:
        eid = e.get("id") or "?"
        key = e.get("key")
        row = index.get(key)
        if row is None:
            errs.append(f'{eid}: sasaran {layer} "{key}" tidak ditemukan di payload')
            continue
        if e.get("op") == "set":
            prov = {"id": eid, "old": {}}
            absent = []
            for k, v in (e.get("set") or {}).items():
                if k in row:
                    prov["old"][k] = row[k]
                else:
                    absent.append(k)
                row[k] = v
            if absent:
                prov["absent"] = absent
            row["_kurasi"] = prov
            rep["set"] += 1
            fields = ", ".join(sorted((e.get("set") or {}).keys()))
            rep["lines"].append(f'~ {layer}/{key} · {row.get("name")} ({fields})')
        else:  # remove
            idx = rows.index(row)
            prov = doc.setdefault("_kurasi", {})
            prov.setdefault("removed", []).append({"index": idx, "row": row})
            rows.pop(idx)
            rep["remove"] += 1
            rep["lines"].append(f'- {layer}/{key} · {row.get("name")}')
    _recount(layer, doc)
    return errs, rep


def _apply_roads(entries, doc):
    errs = []
    rep = {"set": 0, "lines": []}
    for e in entries:
        eid = e.get("id") or "?"
        cls = None
        ruas = None
        for c in doc.get("classes") or []:
            if c.get("key") != e.get("group"):
                continue
            for r in c.get("roads") or []:
                if r.get("n") == e.get("n"):
                    cls, ruas = c, r
                    break
            if ruas:
                break
        if ruas is None:
            errs.append(f'{eid}: ruas {e.get("group")}/{e.get("n")} tidak ditemukan di roads.js')
            continue
        if "kurasi" not in ruas:
            ruas["badge_perda"] = ruas.get("badge")
        ruas["badge"] = f'{CLASS_LABEL[e["class"]]} {BADGE_SUFFIX}'
        ruas["kurasi"] = {
            "id": eid, "class": e["class"], "match": e.get("match") or "",
            "reason": e.get("reason") or "", "source": e.get("source") or "",
        }
        rep["set"] += 1
        rep["lines"].append(f'~ {e.get("group")}/{e.get("n")} · '
                            f'{e.get("match")} -> {ruas["badge"]}')
    return errs, rep


def _recount(layer, doc):
    """Hitung ulang counts turunan setelah patch (provenans menyimpan yang asli)."""
    if layer == "faskes":
        rows = doc.get("list") or []
        by = {}
        for r in rows:
            k = r.get("kind")
            by[k] = by.get(k, 0) + 1
        new = {"total": len(rows), "by_kind": by}
    elif layer == "puskesmas":
        rows = doc.get("list") or []
        new = {"total": len(rows),
               "placed": sum(1 for r in rows if r.get("pin_src")),
               "open24": sum(1 for r in rows if r.get("open24"))}
    else:
        return
    old = doc.get("counts")
    if old == new:
        return
    doc.setdefault("_kurasi", {})["counts"] = old
    doc["counts"] = new


def apply_payload(layer, doc, entries):
    """Pristine (biasanya tak berefek pada rakitan segar) + terapkan entri.

    Kembalikan (doc, galat, mark, laporan); `mark` menandai payload membawa
    kurasi sehingga header berkas memakai varian berpenanda.
    """
    pristine(layer, doc)
    if layer == "roads":
        errs, rep = _apply_roads(entries, doc)
    else:
        errs, rep = _apply_rows(layer, entries, doc)
    return doc, errs, bool(entries), rep


def hook(layer, doc_payload, root=ROOT):
    """Hook skrip build: muat + validasi berkas kurasi lalu terapkan ke payload
    segar. Kembalikan (doc, galat, mark, laporan) — galat tidak kosong berarti
    build harus berhenti dan berkas tidak ditulis."""
    doc = load_doc(root)
    if doc is None:
        doc = empty_doc()
    errs = [f"curated.json tidak sah: {e}" for e in validate(doc)]
    if errs:
        return doc_payload, errs, False, {}
    return apply_payload(layer, doc_payload, entries_for(layer, doc))


def build_kurasi(doc):
    """Payload kurasi.js dari entri add (berkas sepenuhnya milik kurasi)."""
    rows = []
    for e in _adds(doc):
        r = dict(e.get("row") or {})
        r.setdefault("label", r.get("kind") or "")
        r.setdefault("district", "")
        r.setdefault("village", "")
        r.setdefault("reason", e.get("reason") or "")
        r.setdefault("source", e.get("source") or "")
        rows.append(r)
    rows.sort(key=lambda r: (str(r.get("name") or "").casefold(),
                             str(r.get("key") or "")))
    by_kind = {}
    for r in rows:
        k = r.get("kind")
        by_kind[k] = by_kind.get(k, 0) + 1
    return {
        "source": KURASI_SOURCE,
        "generated": "scripts/apply-curated.py",
        "counts": {"total": len(rows), "by_kind": by_kind},
        "list": rows,
    }


def apply_doc(doc, current):
    """Terapkan dokumen kurasi ke payload.

    current = {'schools': (teks, dokumen), 'puskesmas': (…), 'faskes': (…),
               'roads': (…), 'kurasi': teks|None}

    Kembalikan {'files': {relpath: teks_baru}, 'errors': [...], 'report': {...}}.
    `files` hanya memuat berkas yang isinya BERBEDA dari `current`; bila ada
    galat, `files` kosong (tidak ada yang ditulis sebagian).
    """
    errs = validate(doc)
    if errs:
        return {"files": {}, "errors": errs,
                "report": {"validated": False}}

    report = {"validated": True, "layers": {}, "kurasi": None}
    files = {}

    for layer in POI_LAYERS + ("roads",):
        text, payload = current[layer]
        entries = entries_for(layer, doc)
        reverted = pristine(layer, payload)
        if layer == "roads":
            lerrs, rep = _apply_roads(entries, payload)
        else:
            lerrs, rep = _apply_rows(layer, entries, payload)
        errs += lerrs
        if reverted or entries:
            new_text = encode(layer, payload, mark=bool(entries))
            if new_text != text:
                files[_spec(layer)["file"]] = new_text
        report["layers"][layer] = {"reverted": reverted, **rep,
                                   "entries": len(entries)}
    if errs:
        return {"files": {}, "errors": errs, "report": report}

    kurasi_doc = build_kurasi(doc)
    kurasi_text = encode("kurasi", kurasi_doc)
    cur_text = current.get("kurasi")
    if kurasi_text != cur_text:
        files[_spec("kurasi")["file"]] = kurasi_text
    report["kurasi"] = {"total": kurasi_doc["counts"]["total"],
                        "changed": kurasi_text != cur_text}
    return {"files": files, "errors": [], "report": report}


