"""curated — jembatan kurasi Studio Atlas ke payload situs depok-map.

Berkas kontrak: scripts/data/curated.json — DIHASILKAN oleh Studio Atlas
(ensiklopedia-kota, tab Ekspor) dari tools/data/curation.json. Jangan disunting
tangan: seluruh jalur kurasi masuk ke payload situs lewat modul ini.

Dipakai oleh:
  * scripts/apply-curated.py — tulis ulang payload dari kurasi (offline,
    idempoten, reversibel). `--check` memvalidasi sasaran tanpa menulis.
  * scripts/build-*.py       — hook di akhir build, supaya rebuild penuh
    (termasuk lewat Overpass) tetap memuat kurasi.
  * Studio Atlas            — impor modul ini untuk resolusi + pratinjau diff
    (studio menambahkan folder scripts ini ke sys.path).

Format berkas (versi 1) — setiap entri wajib memuat id + reason + source:

  pois[]:
    add     {layer:"kurasi", row:{key,name,kind,label,lat,lon,village,district}}
    set     {layer:"schools|puskesmas|faskes", key, set:{name?, kind?, lat?, lon?}}
    remove  {layer:"schools|puskesmas|faskes", key}

  roads[]:
    set-class {group, n, match, class:"arteri|kolektor|lokal"}

Kaidah reversibilitas: setiap patch menyimpan provenans `_kurasi` di payload
(blok per baris; `_kurasi.removed`/`_kurasi.counts` di tingkat dokumen), dan
header berkas mendapat baris penanda. Menghapus entri lalu menjalankan ulang
apply mengembalikan setiap berkas byte-identik dengan rakitan aslinya — jadi
simpan/kembalikan kurasi tidak pernah meninggalkan jejak yang tak bisa dibaca.

Kaidah kenyaringan: sasaran yang tidak ditemukan atau ambigu = galat keras,
tidak ada yang dilewati diam-diam. `resolve()` (dipakai studio) mengembalikan
galat tersebut sebelum ada berkas apa pun ditulis.
"""
